"""Pack the web page of the clock into the firmware.

Usage: python tools/build_web.py [--check]

web/index.html, style.css and the scripts listed below become one HTML file, compressed with gzip and
written as a C array to components/dekatron_api/web_index.h, which the clock serves from flash.
With --check it only reports the size. The compressed page has to stay small: the application of
the clock has little room left.
"""

import argparse
import gzip
import re
import sys
from pathlib import Path

ROOT = Path(__file__).parent.parent
WEB = ROOT / "web"
OUTPUT = ROOT / "components" / "dekatron_api" / "web_index.h"
SCRIPTS = ("store.js", "timezones.js", "update.js", "app.js")
WARN_BYTES = 70 * 1024
LIMIT_BYTES = 100 * 1024


def squeeze_css(css):
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    css = re.sub(r"\s+", " ", css)
    return re.sub(r"\s*([{};:,>])\s*", r"\1", css).strip()


def build_page():
    page = (WEB / "index.html").read_text(encoding="utf-8")
    css = squeeze_css((WEB / "style.css").read_text(encoding="utf-8"))
    script = "\n".join((WEB / name).read_text(encoding="utf-8") for name in SCRIPTS)
    # A script cannot contain the end of its own tag, or the browser would stop reading it there.
    if "</script" in script:
        sys.exit("A script contains </script")
    page = page.replace("/*STYLE*/", css).replace("/*SCRIPT*/", script)
    if "/*STYLE*/" in page or "/*SCRIPT*/" in page:
        sys.exit("index.html lacks its place for the style or the script")
    return page.encode("utf-8")


def to_header(data):
    lines = [
        "// Generated by tools/build_web.py from web/. Do not edit.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        f"static const uint8_t WEB_INDEX_GZ[{len(data)}] = {{",
    ]
    for start in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{value:02X}" for value in data[start : start + 16]) + ",")
    lines += ["};", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="only report the size")
    args = parser.parse_args()

    page = build_page()
    # The time stamp is left out of the gzip header so the same page always gives the same bytes.
    packed = gzip.compress(page, compresslevel=9, mtime=0)
    print(f"page {len(page)} bytes, compressed {len(packed)} bytes ({len(packed) * 100 // len(page)}%)")
    if len(packed) > LIMIT_BYTES:
        sys.exit(f"The compressed page takes {len(packed)} bytes and the limit is {LIMIT_BYTES}")
    if len(packed) > WARN_BYTES:
        print(f"Warning: over {WARN_BYTES} bytes, which leaves little room for what comes next")
    if not args.check:
        OUTPUT.write_text(to_header(packed), encoding="utf-8")
        print(f"wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
