"""Generate the JPEG test images embedded in the firmware for decode benchmarks."""

import io
import math
import random
from pathlib import Path

from PIL import Image, ImageDraw

WIDTH, HEIGHT = 135, 240
OUTPUT = Path(__file__).parent.parent / "components" / "elekstube_ips" / "bench_jpegs.h"


def photo_like():
    rng = random.Random(1)
    image = Image.new("RGB", (WIDTH, HEIGHT))
    for y in range(HEIGHT):
        for x in range(WIDTH):
            noise = rng.randint(-12, 12)
            r = 128 + 90 * math.sin(x / 11 + y / 23) + noise
            g = 128 + 90 * math.sin(y / 17 - x / 29) + noise
            b = 128 + 90 * math.sin((x + y) / 13) + noise
            image.putpixel((x, y), (int(r), int(g), int(b)))
    return image


def flat_graphic():
    image = Image.new("RGB", (WIDTH, HEIGHT), (10, 14, 30))
    draw = ImageDraw.Draw(image)
    draw.ellipse((18, 30, 117, 129), fill=(240, 180, 40))
    draw.rectangle((30, 150, 105, 170), fill=(40, 200, 120))
    draw.rectangle((30, 185, 105, 205), fill=(220, 60, 70))
    return image


def encode(image, quality):
    buffer = io.BytesIO()
    image.save(buffer, "JPEG", quality=quality, subsampling="4:2:0", progressive=False, optimize=False)
    return buffer.getvalue()


def c_array(name, data):
    rows = [", ".join(f"0x{b:02X}" for b in data[i : i + 16]) for i in range(0, len(data), 16)]
    body = ",\n    ".join(rows)
    return f"static const uint8_t {name}[{len(data)}] = {{\n    {body},\n}};\n"


def main():
    photo = encode(photo_like(), 75)
    graphic = encode(flat_graphic(), 85)
    print(f"photo: {len(photo)} bytes, graphic: {len(graphic)} bytes")
    OUTPUT.write_text(
        "// Generated by tools/make_bench_jpegs.py\n#pragma once\n\n#include <cstdint>\n\n"
        "namespace esphome {\nnamespace elekstube_ips {\n\n"
        + c_array("BENCH_JPEG_PHOTO", photo)
        + "\n"
        + c_array("BENCH_JPEG_GRAPHIC", graphic)
        + "\n}  // namespace elekstube_ips\n}  // namespace esphome\n"
    )


if __name__ == "__main__":
    main()
