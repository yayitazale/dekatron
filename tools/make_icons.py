"""Generate the icons of the setup screen, embedded in the firmware.

They follow the geometry of the wifi and globe icons of Lucide (https://lucide.dev, ISC License),
drawn with a thinner stroke. Each pixel stores a level from 0 to ICON_LEVELS - 1, compressed with
the same RLE as the scenes.
"""

import math
from pathlib import Path

from PIL import Image, ImageDraw

from make_scenes import rle

OUTPUT = Path(__file__).parent.parent / "components" / "elekstube_ips" / "setup_icons.h"
SIZE = 96
ICON_LEVELS = 32
SUPERSAMPLE = 8
UNITS = 24  # the size of the grid the icons are designed on
STROKE = 1.5


def arc_points(start, end, radius, clockwise, steps=120):
    """Points of the short arc between two points, like the A command of SVG."""
    chord = (end[0] - start[0], end[1] - start[1])
    length = math.hypot(*chord)
    side = 1 if clockwise else -1
    height = math.sqrt(radius**2 - (length / 2) ** 2)
    centre = (
        (start[0] + end[0]) / 2 - side * height * chord[1] / length,
        (start[1] + end[1]) / 2 + side * height * chord[0] / length,
    )
    first = math.atan2(start[1] - centre[1], start[0] - centre[0])
    sweep = math.atan2(end[1] - centre[1], end[0] - centre[0]) - first
    sweep = (sweep + math.pi) % (2 * math.pi) - math.pi
    return [
        (centre[0] + radius * math.cos(first + sweep * i / steps), centre[1] + radius * math.sin(first + sweep * i / steps))
        for i in range(steps + 1)
    ]


def stroke(draw, points):
    scale = SIZE * SUPERSAMPLE / UNITS
    radius = STROKE / 2 * scale
    for x, y in points:
        draw.ellipse([x * scale - radius, y * scale - radius, x * scale + radius, y * scale + radius], fill=255)
    pairs = [(x * scale, y * scale) for x, y in points]
    if len(pairs) > 1:
        draw.line(pairs, fill=255, width=round(radius * 2))


def draw_wifi(draw):
    stroke(draw, [(12, 20)])
    stroke(draw, arc_points((2, 8.82), (22, 8.82), 15, True))
    stroke(draw, arc_points((5, 12.859), (19, 12.859), 10, True))
    stroke(draw, arc_points((8.5, 16.429), (15.5, 16.429), 5, True))


def draw_globe(draw):
    stroke(draw, arc_points((12, 2), (22, 12), 10, True))
    stroke(draw, arc_points((22, 12), (12, 22), 10, True))
    stroke(draw, arc_points((12, 22), (2, 12), 10, True))
    stroke(draw, arc_points((2, 12), (12, 2), 10, True))
    stroke(draw, arc_points((12, 2), (12, 22), 14.5, False))
    stroke(draw, arc_points((12, 22), (12, 2), 14.5, False))
    stroke(draw, [(2, 12), (22, 12)])


def render(painter):
    image = Image.new("L", (SIZE * SUPERSAMPLE, SIZE * SUPERSAMPLE))
    painter(ImageDraw.Draw(image))
    return image.resize((SIZE, SIZE), Image.LANCZOS)


def encode(image):
    return rle(bytes(value * ICON_LEVELS // 256 for value in image.tobytes()))


def main():
    lines = [
        "// Generated by tools/make_icons.py, from the icons of Lucide (https://lucide.dev, ISC License).",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace esphome {",
        "namespace elekstube_ips {",
        "",
        f"static constexpr uint8_t SETUP_ICON_SIZE = {SIZE};",
        f"static constexpr uint8_t SETUP_ICON_LEVELS = {ICON_LEVELS};",
        "",
    ]
    for name, painter in (("WIFI", draw_wifi), ("GLOBE", draw_globe)):
        data = encode(render(painter))
        lines.append(f"static const uint8_t SETUP_ICON_{name}[{len(data)}] = {{")
        for start in range(0, len(data), 16):
            lines.append("    " + ", ".join(f"0x{value:02X}" for value in data[start : start + 16]) + ",")
        lines += ["};", ""]
        print(f"{name}: {len(data)} bytes")
    lines += ["}  // namespace elekstube_ips", "}  // namespace esphome", ""]
    OUTPUT.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
