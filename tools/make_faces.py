"""Generate the clock faces embedded in the firmware."""

from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter, ImageFont

from convert import DIGITS, HEIGHT, WIDTH, encode_jpeg

OUTPUT = Path(__file__).parent.parent / "components" / "elekstube_ips" / "faces_builtin.h"
# The firmware carries one face, so the clock always has something to show. The others are made in
# the page, or packed with tools/make_clips.py, and live in the store.
FACES = (
    ("NIXIE", (255, 110, 20), (255, 215, 150)),
)
FONT_SIZE = 200
MESH_STEP = 9


def render_digit(digit, glow, core):
    font = ImageFont.load_default(FONT_SIZE)
    mask = Image.new("L", (WIDTH, HEIGHT))
    draw = ImageDraw.Draw(mask)
    draw.text((WIDTH / 2, HEIGHT / 2), str(digit), fill=255, font=font, anchor="mm")

    image = Image.new("RGB", (WIDTH, HEIGHT))
    mesh = ImageDraw.Draw(image)
    mesh_color = tuple(channel // 12 for channel in glow)
    for x in range(0, WIDTH, MESH_STEP):
        mesh.line((x, 0, x, HEIGHT), fill=mesh_color)
    for y in range(0, HEIGHT, MESH_STEP):
        mesh.line((0, y, WIDTH, y), fill=mesh_color)

    image.paste(Image.new("RGB", image.size, glow), mask=mask.filter(ImageFilter.GaussianBlur(9)))
    image.paste(Image.new("RGB", image.size, glow), mask=mask.filter(ImageFilter.GaussianBlur(3)))
    image.paste(Image.new("RGB", image.size, core), mask=mask)
    return image


def main():
    arrays = []
    tables = []
    total = 0
    for name, glow, core in FACES:
        entries = []
        for digit in range(DIGITS):
            data = encode_jpeg(render_digit(digit, glow, core))
            total += len(data)
            array = f"FACE_{name}_{digit}"
            rows = [", ".join(f"0x{b:02X}" for b in data[i : i + 16]) for i in range(0, len(data), 16)]
            body = ",\n    ".join(rows)
            arrays.append(f"static const uint8_t {array}[{len(data)}] = {{\n    {body},\n}};\n")
            entries.append(f"{{{array}, sizeof({array})}}")
        tables.append("    {" + ", ".join(entries) + "},")
    print(f"{len(FACES)} faces, {total} bytes")
    OUTPUT.write_text(
        "// Generated by tools/make_faces.py\n#pragma once\n\n#include <cstdint>\n\n"
        "namespace esphome {\nnamespace elekstube_ips {\n\n"
        "struct FaceImage {\n  const uint8_t *data;\n  uint32_t size;\n};\n\n"
        + "\n".join(arrays)
        + f"\nstatic constexpr uint8_t BUILTIN_FACE_COUNT = {len(FACES)};\n"
        + f"static const FaceImage BUILTIN_FACES[BUILTIN_FACE_COUNT][{DIGITS}] = {{\n"
        + "\n".join(tables)
        + "\n};\n\n}  // namespace elekstube_ips\n}  // namespace esphome\n"
    )


if __name__ == "__main__":
    main()
